function readingHas(list, id) {
  return (list || []).indexOf(id) !== -1;
}

/**
 * @param {{ pathways?: string[], topics?: string[], capacity?: string }} answers
 * @returns {Array<{ book: object, reason: string, score: number }>}
 */
window.getReadingForPathwayAnswers = function getReadingForPathwayAnswers(answers) {
  answers = answers || {};
  var pathways = answers.pathways || [];
  var topics = answers.topics || [];
  var capacity = answers.capacity || "stretch";
  var books = window.READING_RECOMMENDATIONS || [];
  var scored = [];

  books.forEach(function (book) {
    var match = READING_PATHWAY_MATCH[book.slug];
    if (!match) return;
    if (match.skipCapacity && readingHas(match.skipCapacity, capacity)) return;
    if (match.skipTopics && match.skipTopics.some(function (id) { return readingHas(topics, id); })) {
      return;
    }

    var score = 0;
    (match.pathways || []).forEach(function (id) {
      if (readingHas(pathways, id)) score += match.weight;
    });
    (match.topics || []).forEach(function (id) {
      if (readingHas(topics, id)) score += match.weight + 2;
    });
    if (score <= 0) return;
    scored.push({ book: book, reason: match.reason, score: score });
  });

  scored.sort(function (a, b) {
    return b.score - a.score;
  });

  var limit = capacity === "overwhelm" ? 2 : capacity === "comfort" ? 4 : 3;
  if (readingHas(topics, "teen")) limit = Math.min(limit, 2);

  if (!scored.length) {
    var fallback = books.filter(function (book) {
      return book.slug === "happiness-in-a-nutshell" || book.slug === "feel-the-fear-and-do-it-anyway";
    });
    return fallback.slice(0, limit).map(function (book) {
      return {
        book: book,
        reason: "A starting point if you want something to read alongside the articles.",
        score: 1,
      };
    });
  }

  return scored.slice(0, limit);
};

